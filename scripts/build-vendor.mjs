// Reads the vendor E-IMZO scripts and emits src/core/vendor.ts exporting them as
// string constants, so the auto script loader can inject them inline (self-contained,
// no hosting required by consumers). Run via `npm run build:vendor` (prebuild hook).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

const base = readFileSync(join(root, 'vendor', 'e-imzo.js'), 'utf8')
const client = readFileSync(join(root, 'vendor', 'e-imzo-client.js'), 'utf8')

// JSON.stringify safely escapes quotes, backslashes and newlines into a JS string literal.
const out = `// AUTO-GENERATED by scripts/build-vendor.mjs — do not edit by hand.
// Source: vendor/e-imzo.js and vendor/e-imzo-client.js
/* eslint-disable */

/** Vendor e-imzo.js — defines the \`Base64\` and \`CAPIWS\` globals. Inject FIRST. */
export const VENDOR_BASE: string = ${JSON.stringify(base)}

/** Vendor e-imzo-client.js — defines the \`EIMZOClient\` global. Inject AFTER VENDOR_BASE. */
export const VENDOR_CLIENT: string = ${JSON.stringify(client)}
`

writeFileSync(join(root, 'src', 'core', 'vendor.ts'), out)
console.log('[build-vendor] wrote src/core/vendor.ts (%d + %d bytes)', base.length, client.length)
